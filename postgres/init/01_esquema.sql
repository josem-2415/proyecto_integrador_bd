-- =====================================================================
-- 01_esquema.sql  ·  Esquema de la biblioteca (Hito 2)
-- Se ejecuta SOLO una vez, cuando la base de PostgreSQL se crea vacía.
-- Basado en Data_base_project.sql, con estos agregados:
--   * esquema propio "biblioteca"
--   * CHECKs (la última línea de defensa de la carga)
--   * roles semilla
--   * tabla de bitácora rechazo_carga
--   * extensión pgcrypto (hash de contraseñas)
-- =====================================================================

-- pgcrypto vive en public para que crypt()/gen_salt() se vean desde cualquier search_path
CREATE EXTENSION IF NOT EXISTS pgcrypto SCHEMA public;

DROP SCHEMA IF EXISTS biblioteca CASCADE;
CREATE SCHEMA biblioteca;
SET search_path TO biblioteca, public;

-- ---------- Tipos ----------
CREATE TYPE estado_ejemplar AS ENUM ('disponible', 'prestado', 'baja');
CREATE TYPE estado_prestamo AS ENUM ('activo', 'en_mora', 'devuelto');

-- ---------- Tablas ----------
CREATE TABLE rol (
  id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(30) UNIQUE NOT NULL        -- lector | bibliotecario | administrador | auditor
);

CREATE TABLE usuario (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento     VARCHAR(20)  UNIQUE NOT NULL CHECK (documento <> ''),
  nombres       VARCHAR(100) NOT NULL CHECK (nombres <> ''),
  apellidos     VARCHAR(100) NOT NULL CHECK (apellidos <> ''),
  correo        VARCHAR(150) UNIQUE NOT NULL
                CHECK (correo ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
                CHECK (correo = lower(correo)),
  telefono      VARCHAR(20),
  password_hash VARCHAR(255) NOT NULL,
  activo        BOOLEAN NOT NULL DEFAULT true,
  id_rol        INTEGER NOT NULL
);

CREATE TABLE libro (
  isbn             VARCHAR(13) PRIMARY KEY CHECK (isbn ~ '^[0-9]{13}$'),
  titulo           VARCHAR(200) NOT NULL CHECK (titulo <> ''),
  autor            VARCHAR(150) NOT NULL CHECK (autor <> ''),
  categoria        VARCHAR(80),
  anio_publicacion INTEGER CHECK (anio_publicacion BETWEEN 1450 AND 2100),
  activo           BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE ejemplar (
  isbn            VARCHAR(13) NOT NULL,
  numero_ejemplar INTEGER NOT NULL CHECK (numero_ejemplar > 0),
  estado          estado_ejemplar NOT NULL DEFAULT 'disponible',
  PRIMARY KEY (isbn, numero_ejemplar)
);

CREATE TABLE prestamo (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lector                 INTEGER NOT NULL,   -- usuario con rol lector (trigger en un hito posterior)
  isbn                      VARCHAR(13) NOT NULL,
  numero_ejemplar           INTEGER NOT NULL,
  id_bibliotecario          INTEGER NOT NULL,   -- usuario con rol bibliotecario (trigger en un hito posterior)
  fecha_prestamo            DATE NOT NULL,
  fecha_esperada_devolucion DATE NOT NULL,
  estado                    estado_prestamo NOT NULL DEFAULT 'activo',
  CHECK (fecha_esperada_devolucion >= fecha_prestamo)
);

CREATE TABLE devolucion (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prestamo      INTEGER UNIQUE NOT NULL,
  id_bibliotecario INTEGER NOT NULL,
  fecha_devolucion DATE NOT NULL
);

-- Bitácora de filas rechazadas durante las cargas desde CSV
CREATE TABLE rechazo_carga (
  id        INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  archivo   TEXT        NOT NULL,
  linea     INTEGER     NOT NULL,   -- número de línea en el archivo (la 1 es el encabezado)
  contenido TEXT        NOT NULL,   -- la línea original, sin tocar
  motivo    TEXT        NOT NULL,
  fecha     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- Llaves foráneas ----------
ALTER TABLE usuario    ADD FOREIGN KEY (id_rol)           REFERENCES rol (id)                 ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE ejemplar   ADD FOREIGN KEY (isbn)             REFERENCES libro (isbn)             ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE prestamo   ADD FOREIGN KEY (id_lector)        REFERENCES usuario (id)             ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE prestamo   ADD FOREIGN KEY (isbn, numero_ejemplar) REFERENCES ejemplar (isbn, numero_ejemplar) ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE prestamo   ADD FOREIGN KEY (id_bibliotecario) REFERENCES usuario (id)             ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE devolucion ADD FOREIGN KEY (id_prestamo)      REFERENCES prestamo (id)            ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE devolucion ADD FOREIGN KEY (id_bibliotecario) REFERENCES usuario (id)             ON DELETE RESTRICT DEFERRABLE INITIALLY IMMEDIATE;

-- ---------- Datos mínimos ----------
